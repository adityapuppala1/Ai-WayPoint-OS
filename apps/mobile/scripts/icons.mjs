const WEIGHTS = ['regular', 'fill'];

function pathsFor(phosphorName) {
  const src = readFileSync(join(pkgDir, 'src/defs', `${phosphorName}.tsx`), 'utf8');
  const out = {};
  for (const weight of WEIGHTS) {
    const block = new RegExp(`\\[\\s*'${weight}',\\s*<>([\\s\\S]*?)</>`).exec(src);
    if (!block) throw new Error(`${phosphorName}: no ${weight} weight`);
    const body = block[1];
    const elements = [...body.matchAll(/<(\w+)/g)].map((m) => m[1]);
    if (elements.some((e) => e !== 'Path'))
      throw new Error(
        `${phosphorName} (${weight}) uses ${elements.join(', ')}; only paths are supported`,
      );
    out[weight] = [...body.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1]).join(' ');
  }
  return out;
}

const lines = Object.entries(ICONS).map(([name, phosphor]) => {
  const p = pathsFor(phosphor);
  return `  ${name}: {\n    regular: '${p.regular}',\n    fill: '${p.fill}',\n  },`;
});

const file = `// Generated by scripts/icons.mjs from phosphor-react-native ${version}
// (MIT License, Phosphor Icons — https://phosphoricons.com). Do not edit by hand.

export const ICON_PATHS = {
${lines.join('\n')}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;

writeFileSync(join(here, '../src/ui/icon-paths.ts'), file);
console.log(`Wrote ${Object.keys(ICONS).length} icons.`);
