#!/usr/bin/env node
/**
 * Writes src/ui/icon-paths.ts: the path data of the few Phosphor icons the app uses, in the
 * two weights it uses. The web app uses the same icons (packages/ui/src/icons.ts) under the
 * same names. Shipping only these keeps the bundle small (phosphor-react-native has 1,500
 * icons in six weights).
 *
 *   node scripts/icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// The package doesn't export its package.json, so find it through node_modules.
const pkgDir = join(here, '../node_modules/phosphor-react-native');
const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));

/** Waypoint's name for each icon → Phosphor's. Keep in step with packages/ui/src/icons.ts. */
